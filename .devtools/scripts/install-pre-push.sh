#!/usr/bin/env bash
# install-pre-push.sh -- put the leak check in front of prek's pre-push hook.
#
# prek reads git's pre-push input itself and hands its hooks none of it,
# so a check that runs as a prek hook can't see which refs and objects a
# push sends. This keeps prek's generated hook as pre-push.prek and writes
# a pre-push that runs the leak check with git's own arguments and ref
# lines, then runs the prek hook with the same arguments and lines.
#
# Run it after `prek install`, which bootstrap does. It is safe to rerun:
# prek install moves a foreign pre-push aside as pre-push.legacy and
# writes its own, and this puts the wrapper back in front.
#
#   install-pre-push.sh            install or refresh the wrapper
#   install-pre-push.sh --check    exit 1 unless the wrapper is installed;
#                                  exit 0 without looking in CI
set -euo pipefail

marker='# check-leaks pre-push wrapper'

hooks=$(git rev-parse --git-path hooks)
hooks=$(cd "$hooks" 2>/dev/null && pwd) || {
  echo "install-pre-push: no hooks directory; run prek install first" >&2
  exit 1
}

wrapper() {
  cat <<'WRAPPER'
#!/bin/sh
# check-leaks pre-push wrapper (installed by .devtools/scripts/install-pre-push.sh).
# Runs the leak check on the ref lines git gives this hook, then runs
# prek's hook with the same arguments and lines.
hooks=$(cd "$(dirname "$0")" && pwd)
input=$(mktemp) || exit 1
trap 'rm -f "$input"' EXIT
# A failed copy would leave an empty file, which reads as nothing to push.
if ! cat >"$input"; then
  echo "check-leaks: could not read the push from git; the push is blocked" >&2
  exit 1
fi
if [ -f .devtools/scripts/check-leaks.sh ]; then
  mise run --quiet devtools:lint-leaks -- --pre-push-hook "$@" <"$input" || exit 1
else
  echo "check-leaks: the leak check is not present on this branch and was skipped" >&2
fi
"$hooks/pre-push.prek" "$@" <"$input"
WRAPPER
}

is_wrapper() { [[ -f $1 ]] && grep -qF "$marker" "$1"; }
is_prek() { [[ -f $1 ]] && grep -qF 'File generated by prek' "$1"; }

if [[ ${1-} == --check ]]; then
  if [[ -n ${CI-} ]]; then
    echo "install-pre-push: CI has no local hooks to check"
    exit 0
  fi
  # A read that prints the right hook and then fails is no proof it's installed.
  expected=$(wrapper)
  if is_wrapper "$hooks/pre-push" && is_prek "$hooks/pre-push.prek" &&
    installed=$(cat "$hooks/pre-push") && [[ $installed == "$expected" ]]; then
    exit 0
  fi
  echo "install-pre-push: the leak-check pre-push hook isn't installed; run mise run bootstrap" >&2
  exit 1
fi

if is_prek "$hooks/pre-push"; then
  # Replace an earlier copy of prek's hook, never anything else.
  if [[ -e $hooks/pre-push.prek ]] && ! is_prek "$hooks/pre-push.prek"; then
    echo "install-pre-push: pre-push.prek exists and isn't a prek hook; move it aside first" >&2
    exit 1
  fi
  mv "$hooks/pre-push" "$hooks/pre-push.prek"
  # prek install parks a hook it didn't write as pre-push.legacy. If that
  # was this wrapper, the prek hook is now in front of it again.
  if is_wrapper "$hooks/pre-push.legacy"; then
    rm -f "$hooks/pre-push.legacy"
  fi
elif ! is_wrapper "$hooks/pre-push"; then
  echo "install-pre-push: pre-push is neither prek's hook nor this wrapper; run prek install first" >&2
  exit 1
fi
if ! is_prek "$hooks/pre-push.prek"; then
  echo "install-pre-push: pre-push.prek isn't a prek hook; run prek install first" >&2
  exit 1
fi
wrapper >"$hooks/pre-push"
chmod +x "$hooks/pre-push"
echo "install-pre-push: leak check installed in front of prek's pre-push hook"
