package hygiene

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"slices"
	"strconv"
	"strings"
)

var errIncompleteFinding = errors.New("incomplete structural finding")

func diagnostics(data []byte) ([]string, error) {
	decoder := json.NewDecoder(bytes.NewReader(data))
	var lines []string
	for {
		var item struct {
			File  string `json:"file"`
			Range struct {
				Start struct {
					Line *int `json:"line"`
				} `json:"start"`
			} `json:"range"`
			RuleID  *string `json:"ruleId"`
			Message *string `json:"message"`
		}
		err := decoder.Decode(&item)
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return nil, fmt.Errorf("decode: %w", err)
		}
		// The frozen selector ignores objects without a file.
		if item.File == "" {
			continue
		}
		if item.Range.Start.Line == nil || *item.Range.Start.Line < 0 || item.RuleID == nil || item.Message == nil {
			return nil, errIncompleteFinding
		}
		lines = append(
			lines,
			item.File+"\t"+strconv.Itoa(*item.Range.Start.Line+1)+"\t"+*item.RuleID+"\t"+*item.Message,
		)
	}
	slices.SortFunc(lines, compareDiagnostic)
	return lines, nil
}

func compareDiagnostic(a, b string) int {
	const columns = 3
	af, bf := strings.SplitN(a, "\t", columns), strings.SplitN(b, "\t", columns)
	if cmp := strings.Compare(af[0], bf[0]); cmp != 0 {
		return cmp
	}
	// Line numbers are positive decimal integers generated by the decoder.
	if len(af[1]) < len(bf[1]) {
		return -1
	}
	if len(af[1]) > len(bf[1]) {
		return 1
	}
	if cmp := strings.Compare(af[1], bf[1]); cmp != 0 {
		return cmp
	}
	return strings.Compare(a, b)
}
